#!/usr/bin/env -S deno run --allow-read --allow-write --allow-env --allow-net
/// <reference lib="deno.ns" />
/**
 * Build script for AudioWorklet processors
 *
 * This script:
 * 1. Generates audio/audio_worklet_names.ts, the processors' names, from the
 *    package version in deno.json
 * 2. Bundles worklet TypeScript files to JavaScript
 * 3. Generates TypeScript files that export the worklet code as strings
 * 4. Allows importing worklets as inline code instead of external files
 */

import { basename, dirname, fromFileUrl, join } from "https://deno.land/std@0.208.0/path/mod.ts";
import * as esbuild from "https://deno.land/x/esbuild@v0.20.1/mod.js";

// Get the directory where this script is located
const __dirname = dirname(fromFileUrl(import.meta.url));
// Audio worklet files are in the audio directory
const audioDir = join(__dirname, "..", "audio");
const packageConfigFile = join(__dirname, "..", "deno.json");
const namesFile = join(audioDir, "audio_worklet_names.ts");

const WORKLET_FILES = [
	join(audioDir, "capture_worklet.ts"),
	join(audioDir, "playout_worklet.ts"),
	join(audioDir, "voice_activity_worklet.ts"),
];

interface WorkletInfo {
	sourceFile: string;
	outputFile: string;
	exportName: string;
}

function getWorkletInfo(sourceFile: string): WorkletInfo {
	const baseName = basename(sourceFile, ".ts");
	const dir = dirname(sourceFile);
	const outputFile = join(dir, `${baseName}_inline.ts`);
	// Convert capture_worklet -> CaptureCode, playout_worklet -> PlayoutCode
	let exportName: string;
	if (baseName.includes("capture")) {
		exportName = "CaptureCode";
	} else if (baseName.includes("playout")) {
		exportName = "PlayoutCode";
	} else if (baseName.includes("voice_activity")) {
		exportName = "VoiceActivityCode";
	} else {
		// Fallback: convert capture_worklet -> captureWorkletCode
		exportName = baseName
			.split("_")
			.map((part, i) => i === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1))
			.join("") + "Code";
	}

	return { sourceFile, outputFile, exportName };
}

// The package version in the deno.json at `path`.
async function readPackageVersion(path: string): Promise<string> {
	const config: unknown = JSON.parse(await Deno.readTextFile(path));
	if (
		typeof config !== "object" || config === null || !("version" in config) ||
		typeof config.version !== "string" || config.version === ""
	) {
		throw new Error(`${path} has no version`);
	}
	return config.version;
}

// Writes the processors' names for `version`, which the worklets register
// under and the nodes create their AudioWorkletNodes with.
async function writeProcessorNames(version: string): Promise<void> {
	console.log(`🔨 Generating ${basename(namesFile)} for version ${version}...`);

	const tsContent = `// Auto-generated file - do not edit manually
// Generated by scripts/build_worklets.ts from the version in deno.json

// The package version is part of each processor's name, so copies of av-nodes
// of different versions can share a scope, each registering and using its own
// processors.

/** Name the playout processor is registered under. */
export const PLAYOUT_PROCESSOR_NAME = ${JSON.stringify(`@okdaichi/av-nodes/playout@${version}`)};

/** Name the capture processor is registered under. */
export const CAPTURE_PROCESSOR_NAME = ${JSON.stringify(`@okdaichi/av-nodes/capture@${version}`)};

/** Name the voice activity (VAD) processor is registered under. */
export const VAD_PROCESSOR_NAME = ${JSON.stringify(`@okdaichi/av-nodes/vad@${version}`)};
`;

	await Deno.writeTextFile(namesFile, tsContent);
	await formatFile(namesFile);

	console.log(`✅ Generated ${basename(namesFile)}`);
}

// Formats the generated file at `path` according to deno.json fmt settings.
async function formatFile(path: string): Promise<void> {
	const fmt = new Deno.Command("deno", { args: ["fmt", path] });
	const fmtResult = await fmt.output();
	if (!fmtResult.success) {
		throw new Error(`deno fmt failed for ${basename(path)}`);
	}
}

async function buildWorklet(info: WorkletInfo): Promise<void> {
	const baseName = basename(info.sourceFile);
	const outputBaseName = basename(info.outputFile);
	console.log(`🔨 Building ${baseName} → ${outputBaseName}...`);

	// Bundle the worklet code
	const result = await esbuild.build({
		entryPoints: [info.sourceFile],
		bundle: true,
		format: "esm",
		write: false,
		minify: true,
		target: "es2022",
	});

	if (result.outputFiles.length === 0) {
		throw new Error(`No output files generated for ${info.sourceFile}`);
	}

	const outputFile = result.outputFiles[0];
	if (!outputFile) {
		throw new Error(`Output file is undefined for ${info.sourceFile}`);
	}

	let code = new TextDecoder().decode(outputFile.contents);

	// Remove export statements - worklet doesn't need them
	code = code.replace(/export\s*\{[^}]*\}\s*;?\s*$/gm, "");
	code = code.replace(/export\s+(const|function|class)\s+/g, "$1 ");

	// Remove importWorkletUrl function (not needed in inline version)
	code = code.replace(
		/function\s+\w+\(\)\{return new URL\([^)]+\)\.href\}/g,
		"",
	);

	// Generate TypeScript file with inline code
	const tsContent = `// Auto-generated file - do not edit manually
// Generated from ${basename(info.sourceFile)}

/**
 * Inline worklet code for ${basename(info.sourceFile, ".ts")}
 * This code is bundled and minified at build time.
 */
export const ${info.exportName} = ${JSON.stringify(code)};

/**
 * Create a Blob URL for the worklet code
 * Use this with audioContext.audioWorklet.addModule()
 */
export function createWorkletBlobUrl(): string {
	const blob = new Blob([${info.exportName}], { type: "application/javascript" });
	return URL.createObjectURL(blob);
}
`;

	// Write the generated file
	await Deno.writeTextFile(info.outputFile, tsContent);

	await formatFile(info.outputFile);

	console.log(`✅ Generated ${basename(info.outputFile)}`);
}

async function main() {
	console.log("🚀 Building AudioWorklet processors...\n");

	const version = await readPackageVersion(packageConfigFile);
	await writeProcessorNames(version);

	for (const sourceFile of WORKLET_FILES) {
		const info = getWorkletInfo(sourceFile);
		await buildWorklet(info);
	}

	console.log("\n✨ All worklets built successfully!");
	console.log("\nNext steps:");
	console.log(
		"1. Update encode_node.ts and decode_node.ts to import from *_inline.ts files",
	);
	console.log("2. Use createWorkletBlobUrl() instead of importWorkletUrl()");
}

// Run the build
if (import.meta.main) {
	try {
		await main();
		esbuild.stop();
	} catch (error) {
		console.error("❌ Build failed:", error);
		esbuild.stop();
		Deno.exit(1);
	}
}
